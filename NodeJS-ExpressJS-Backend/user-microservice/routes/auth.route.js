const express = require("express");

const router = express.Router();

const {
    registerUser,
    loginUser,
    logoutUser
} = require("../controllers/auth.controller.js");



// ============================================================
// Register user - starts
// ============================================================
router.post(
    "/register",
    registerUser
);
// ============================================================
// Register user - ends
// ============================================================



// ============================================================
// Login user - starts
// ============================================================
router.post(
    "/login",
    loginUser
);
// ============================================================
// Login user - ends
// ============================================================



// ============================================================
// Logout user - starts
// ============================================================
router.post(
    "/logout",
    logoutUser
);
// ============================================================
// Logout user - ends
// ============================================================



// ============================================================
// Router Export - starts
// ============================================================
module.exports = router;
// ============================================================
// Router Export - ends
// ============================================================